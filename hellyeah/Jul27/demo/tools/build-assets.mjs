import { readFile, writeFile } from 'node:fs/promises';
const base = new URL('../', import.meta.url);
const assets = { INDEX: 'index.html', STYLE: 'style.css', MOTION: 'motion.js', RENDERER: 'renderer.js', SERIAL: 'serial.js', APP: 'app.js' };
let output = '// Generated by node tools/build-assets.mjs. Edit web/ files, then regenerate.\n#pragma once\n#include <Arduino.h>\n';
for (const [name, file] of Object.entries(assets)) {
  const source = await readFile(new URL(`web/${file}`, base), 'utf8');
  if (source.includes(')DEMO_ASSET"')) throw new Error(`Raw-string delimiter collision in ${file}`);
  output += `\nstatic const char ASSET_${name}[] PROGMEM = R"DEMO_ASSET(${source})DEMO_ASSET";\n`;
}
const target = new URL('WebAssets.h', base);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('WebAssets.h is stale. Run npm run build.');
  console.log('Embedded assets match web sources.');
} else {
  await writeFile(target, output);
  console.log(`Generated WebAssets.h (${Buffer.byteLength(output)} bytes).`);
}
